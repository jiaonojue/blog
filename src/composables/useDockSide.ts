/**
 * 顶栏停靠位 —— 「顶栏是玩具」的那一半。
 *
 * 【这是个什么玩具】
 *   顶上的胶囊平时居中。当你点了一个靠左的栏目（首页、文章），
 *   它就飞到屏幕左边、竖起来变成一条侧栏；点靠右的栏目（相册、关于）
 *   就飞到右边。点中间的栏目，或者点左上角的印章，它回到居中。
 *   飞行本身是一段带空翻的弹性动画——它就是网站的玩具之一，
 *   除了好玩没有任何用途。
 *
 * 【为什么放在模块里而不是组件里】
 *   停靠位要跟着路由走：在文章页把顶栏停到了右边，
 *   切到收藏页它还停在右边，直到你点了别的方位的栏目。
 *   模块级 ref 在整个 SPA 会话里存活；刷新页面就回到居中，
 *   这也是故意的——玩具不该被记住太久。
 *
 * 【什么时候不出玩具】
 *   窄屏（<1366px）内容会顶到屏幕边，侧栏会压住正文，所以不生效；
 *   摸鱼分区（附录）时顶栏本来就要滑到底部，侧栏让位；
 *   动效开关关掉时直接换位置，不飞。
 */
import { ref } from 'vue'

export type DockSide = 'center' | 'left' | 'right'

/** 当前停靠位。模块级：路由之间共享，刷新即回中 */
export const dockSide = ref<DockSide>('center')

/** 侧栏生效的最小视口宽度。再窄正文会顶到屏幕边 */
export const DOCK_SIDE_MIN_WIDTH = 1366

export function setDockSide(side: DockSide): void {
  dockSide.value = side
}
